<h1>Van contentidee tot publicatie.</h1>
<p class="intro">BBQuality The Pitboard is de interne werkomgeving voor het marketingteam van BBQuality. Het team bereidt content voor, bespreekt deze en plant publicaties op de eigen bedrijfskanalen.</p>
<h2>Wat doet Pitboard?</h2>
<ul>
    <li>Projecten, taken en contentplannen op één plek organiseren.</li>
    <li>Teksten, afbeeldingen en video's voorbereiden en laten beoordelen.</li>
    <li>Goedgekeurde content inplannen voor de gekoppelde Facebook-pagina, Instagram en YouTube.</li>
    <li>Per publicatie controleren of het platform de content heeft ontvangen en verwerkt.</li>
</ul>
<h2>Jij bepaalt het kanaal en het publicatiemoment</h2>
<p>Alleen bevoegde BBQuality-gebruikers kunnen inloggen. Een beheerder koppelt de bedrijfsaccounts via het toestemmingsscherm van het platform. Het team controleert het account, de tekst, de media en de zichtbaarheid voordat een publicatie wordt ingepland.</p>
<p>Pitboard gebruikt YouTube API Services om het gekozen kanaal te herkennen, video's te uploaden en de verwerking te controleren. Een Google-account koppelen geeft geen toegang tot Gmail of Google Drive. Andere Google-accounts waarmee je browser is ingelogd worden niet automatisch gekoppeld.</p>
<p class="note">Een concept opslaan of een account koppelen publiceert nog niets. Automatisch publiceren vereist een ingeschakelde verbinding, een goedgekeurde versie, een bevestigde planning en een werkende serveruitvoerder.</p>
